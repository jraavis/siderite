//! `siderite generate ci [--update] [--dry-run]`: a GitHub Actions
//! workflow, `.github/workflows/siderite.yml` at the repository root,
//! running the same verification contract as `siderite verify`.
//!
//! - The `verify` job runs `siderite verify --json` on every push and
//!   pull request and keeps the report as an artifact.
//! - The `live` job runs `siderite verify --live --json` only when asked
//!   (by hand) or on `main`, with database service containers for the
//!   backends the CLI is built with; they use trust authentication, so
//!   the workflow holds no passwords or other secrets.
//! - The toolchain is pinned: `rust-toolchain.toml`, else the package's
//!   `rust-version`, else the `rustc` in use now.
//! - The CLI is installed from the exact source `Cargo.lock` pins.
//!
//! An existing workflow is never overwritten. `--update` replaces only a
//! file this generator wrote (it starts with [`MARKER`]); combine it with
//! `--dry-run` to review the change first.

use crate::docs::version::locked_source;
use crate::error::CliError;
use crate::workspace::Package;
use serde_json::Value;
use std::fmt::Write;
use std::path::{Path, PathBuf};

/// The first line of a generated workflow.
pub(crate) const MARKER: &str = "# Generated by `siderite generate ci`.";

/// Where the workflow is written, relative to the repository root.
pub(crate) const FILE: &str = ".github/workflows/siderite.yml";

const CLI: &str = "siderite-cli";

type Found<T> = Result<T, CliError>;
/// A shell command, or why it cannot be written.
type Command = Found<String>;

/// Parsed `generate ci` arguments.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct CiOptions {
    /// `--update`: replace a workflow this generator wrote.
    pub update: bool,
}

/// Parse the words after `generate ci`.
///
/// Errors:
///   A usage error for anything but `--update`.
pub(crate) fn parse(words: &[String]) -> Found<CiOptions> {
    let mut update = false;
    for word in words {
        if word != "--update" {
            let msg = format!(
                "unexpected argument `{word}`; usage: generate ci \
                 [--update] [--dry-run]"
            );
            return Err(CliError::usage(msg));
        }
        update = true;
    }
    Ok(CiOptions { update })
}

/// Whether `--update` may replace `existing`: only a workflow this
/// generator wrote. Without `--update` the write plan refuses any
/// different existing file.
///
/// Errors:
///   A conflict for `--update` on a workflow written by hand.
pub(crate) fn may_replace(existing: Option<&str>, update: bool) -> Found<()> {
    let foreign = existing.is_some_and(|t| !t.starts_with(MARKER));
    if update && foreign {
        return Err(CliError::Conflict(format!(
            "{FILE} was not written by `siderite generate ci`; it is \
             never replaced"
        )));
    }
    Ok(())
}

/// The repository root above `dir` (the nearest `.git`), else `dir`.
pub(crate) fn repository(dir: &Path) -> PathBuf {
    let found = dir.ancestors().find(|d| d.join(".git").exists());
    found.unwrap_or(dir).to_path_buf()
}

/// Everything the workflow is made of.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Inputs {
    /// The package directory relative to the repository (`` for the
    /// root), with `/` separators.
    pub working_dir: String,
    /// The pinned toolchain and where it came from.
    pub toolchain: (String, &'static str),
    /// The shell command installing the CLI.
    pub install: String,
    /// Database backends of the live job: `postgres`, `mysql`.
    pub databases: Vec<&'static str>,
}

/// The toolchain: the toolchain file's channel, else `rust_version`,
/// else `current` (`rustc --version` output).
pub(crate) fn toolchain(
    dir: &Path,
    rust_version: Option<&str>,
    current: &str,
) -> (String, &'static str) {
    for file in ["rust-toolchain.toml", "rust-toolchain"] {
        let mut candidates = dir.ancestors().map(|d| d.join(file));
        let Some(path) = candidates.find(|p| p.is_file()) else {
            continue;
        };
        let text = std::fs::read_to_string(path).unwrap_or_default();
        if let Some(channel) = channel(&text) {
            return (channel, "toolchain file");
        }
    }
    if let Some(version) = rust_version {
        return (version.to_owned(), "rust-version");
    }
    let version = current.split_whitespace().nth(1).unwrap_or("stable");
    (version.to_owned(), "current rustc")
}

/// `channel = "X"` of a TOML toolchain file, or a legacy one-line file.
fn channel(text: &str) -> Option<String> {
    for line in text.lines().map(str::trim) {
        if let Some(rest) = line.strip_prefix("channel") {
            let value = rest.trim_start().strip_prefix('=')?.trim();
            return Some(value.trim_matches('"').to_owned());
        }
    }
    let line = text.lines().next()?.trim();
    let legacy = !line.is_empty() && !line.contains(['=', '[']);
    legacy.then(|| line.to_owned())
}

/// The CLI dependency of `package`, as `cargo metadata` lists it.
fn cli_spec(package: &Package) -> Option<&Value> {
    let name = |d: &&Value| d.get("name").and_then(Value::as_str) == Some(CLI);
    package.specs.iter().find(name)
}

/// The CLI features the package enables.
fn features(spec: Option<&Value>) -> Vec<String> {
    let listed = spec.and_then(|s| s.get("features")?.as_array().cloned());
    let listed = listed.unwrap_or_default();
    listed
        .iter()
        .filter_map(Value::as_str)
        .map(str::to_owned)
        .collect()
}

/// `cargo install` for the CLI exactly as `lock` pins it.
///
/// Errors:
///   A usage error when the CLI is not locked, or comes from a path
///   outside `repo`.
pub(crate) fn install(pkg: &Package, lock: &str, repo: &Path) -> Command {
    let spec = cli_spec(pkg);
    let mut command = String::from("cargo install --locked");
    match locked_source(lock, CLI) {
        Some((_, source)) if source.starts_with("git+") => {
            let rest = &source["git+".len()..];
            let (url, commit) = rest.split_once('#').unwrap_or((rest, ""));
            let url = url.split('?').next().unwrap_or(url);
            let _ = write!(command, " --git {url}");
            if !commit.is_empty() {
                let _ = write!(command, " --rev {commit}");
            }
            let _ = write!(command, " {CLI}");
        }
        Some((version, _)) => {
            let _ = write!(command, " {CLI} --version ={version}");
        }
        None => {
            let path = spec.and_then(|s| s.get("path")?.as_str());
            let missing = || {
                CliError::usage(
                    "siderite-cli is not in Cargo.lock; run `siderite \
                     build` once, then commit Cargo.lock",
                )
            };
            let path = Path::new(path.ok_or_else(missing)?);
            let rel = path.strip_prefix(repo).map_err(|_| {
                CliError::usage(
                    "siderite-cli comes from a path outside the \
                     repository, which CI cannot install",
                )
            })?;
            let rel = rel.to_string_lossy().replace('\\', "/");
            let root = "${{ github.workspace }}";
            let _ = write!(command, " --path {root}/{rel}");
        }
    }
    let features = features(spec);
    if !features.is_empty() {
        let _ = write!(command, " --features {}", features.join(","));
    }
    Ok(command)
}

/// The live job's databases, from the CLI features.
pub(crate) fn databases(package: &Package) -> Vec<&'static str> {
    let features = features(cli_spec(package));
    let has = |name: &str| features.iter().any(|f| f == name);
    ["postgres", "mysql"]
        .into_iter()
        .filter(|db| has(db))
        .collect()
}

const PG_URL: &str = "      DATABASE_URL: \
                      postgres://postgres@localhost:5432/app\n";
const MYSQL_URL: &str = "      MYSQL_URL: mysql://root@127.0.0.1:3306/app\n";
/// Only by hand, or on `main`.
const LIVE_WHEN: &str = "github.event_name == 'workflow_dispatch' || \
                         github.ref == 'refs/heads/main'";

const POSTGRES: &str = "      postgres:
        image: postgres:17-alpine
        env:
          POSTGRES_HOST_AUTH_METHOD: trust
          POSTGRES_DB: app
        ports: [\"5432:5432\"]
        options: >-
          --health-cmd \"pg_isready -U postgres\" --health-interval 2s
          --health-timeout 5s --health-retries 30
";

const MYSQL: &str = "      mysql:
        image: mysql:8.4
        env:
          MYSQL_ALLOW_EMPTY_PASSWORD: \"yes\"
          MYSQL_DATABASE: app
        ports: [\"3306:3306\"]
        options: >-
          --health-cmd \"mysqladmin ping -h 127.0.0.1\" --health-interval 2s
          --health-timeout 5s --health-retries 30
";

/// The steps both jobs share, up to and including the CLI install.
fn setup(inputs: &Inputs) -> String {
    let (toolchain, source) = &inputs.toolchain;
    format!(
        "      - uses: actions/checkout@v4
      # Pinned from the {source}.
      - uses: dtolnay/rust-toolchain@master
        with:
          toolchain: \"{toolchain}\"
          components: rustfmt, clippy
      - uses: Swatinem/rust-cache@v2
      - name: Install the siderite CLI (as Cargo.lock pins it)
        run: {install}
",
        install = inputs.install
    )
}

/// The steps running one verification and keeping its report.
fn verify(flags: &str, report: &str) -> String {
    format!(
        "      - name: siderite verify{flags}
        run: |
          set -o pipefail
          siderite verify{flags} --json | tee {report}.json
      - name: Keep the report
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: {report}
          path: {wd}{report}.json
          if-no-files-found: ignore
",
        wd = "${{ env.PACKAGE_DIR }}"
    )
}

/// The workflow.
pub(crate) fn render(inputs: &Inputs) -> String {
    let mut services = String::new();
    let mut env = String::new();
    for db in &inputs.databases {
        if *db == "postgres" {
            services.push_str(POSTGRES);
            env.push_str(PG_URL);
        } else {
            services.push_str(MYSQL);
            env.push_str(MYSQL_URL);
        }
    }
    let services = if services.is_empty() {
        String::new()
    } else {
        format!("    services:\n{services}")
    };
    let env = if env.is_empty() {
        String::new()
    } else {
        format!("    env:\n{env}")
    };
    let dir = if inputs.working_dir.is_empty() {
        String::new()
    } else {
        format!("{}/", inputs.working_dir)
    };
    let defaults = if inputs.working_dir.is_empty() {
        String::new()
    } else {
        format!(
            "\ndefaults:\n  run:\n    working-directory: {}\n",
            inputs.working_dir
        )
    };
    let setup = setup(inputs);
    format!(
        "\
{MARKER}
# `siderite generate ci --update --dry-run` shows how a regenerated
# workflow differs; nothing here is a secret.
name: siderite

on:
  push:
    branches: [main]
  pull_request:
  workflow_dispatch:

permissions:
  contents: read

env:
  CARGO_TERM_COLOR: always
  PACKAGE_DIR: \"{dir}\"
{defaults}
jobs:
  verify:
    runs-on: ubuntu-latest
    steps:
{setup}{offline}
  # Live-service tests run only when asked for (by hand) and on main.
  live:
    if: {LIVE_WHEN}
    needs: verify
    runs-on: ubuntu-latest
{services}{env}    steps:
{setup}{live}",
        offline = verify("", "verify"),
        live = verify(" --live", "verify-live"),
    )
}

/// The registration-free next steps.
pub(crate) fn instructions(inputs: &Inputs) -> String {
    let (toolchain, source) = &inputs.toolchain;
    let mut out = format!(
        "The workflow pins Rust {toolchain} (from the {source}) and installs \
         the CLI with:\n  {}\n",
        inputs.install
    );
    if inputs.databases.is_empty() {
        out.push_str("The live job has no database services (SQLite).\n");
    }
    out.push_str("Commit it; the live job runs on main or by hand.\n");
    out
}
